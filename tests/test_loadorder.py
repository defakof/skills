class TestConflictScan(LoBase):
    def scanner(self, **kw):
        m = self.model(**kw)
        return m, conflicts.Scanner(m)

    def test_quick(self):
        m, sc = self.scanner()
        confl = sc.conflicts()
        cats = {c.category for c in confl}
        self.assertTrue({'navmesh', 'leveled', 'npc', 'items', 'settings', 'cells', 'placed'} <= cats)
        lvl = [c for c in confl if c.sig == 'LVLI'][0]
        self.assertEqual(lvl.winner.entry.name, 'LateOverride.esp')
        over = sc.overridden_patches(confl)
        self.assertIn(('ModA - ModB Patch.esp', 'LateOverride.esp'), over)
        self.assertNotIn('Bashed Patch, 0.esp', [p for p, _w in over])     # generated patches are not "patches"
        dirty = sc.dirty()
        self.assertEqual(list(dirty), ['Dirty.esp'])
        self.assertEqual((dirty['Dirty.esp']['udr'], dirty['Dirty.esp']['deleted_navmesh']), (1, 1))
        self.assertEqual(len(dirty['Dirty.esp']['refs']), 1)
        self.assertEqual(len(sc.navmesh_cells()), 1)
        self.assertEqual([e for e, _w in sc.edid_duplicates()], ['SharedName'])
        _inj, coll = sc.injected()
        self.assertEqual(len(coll), 1)
        rev = sc.official_reverts()
        self.assertEqual(list(rev), ['Reverter.esp'])
        self.assertEqual(rev['Reverter.esp']['fixers'], ['Update.esm'])

    def test_deep(self):
        m, sc = self.scanner()
        lo = LoadOrder(m.data_dir)
        dc = conflicts.DeepComparer(sc, lo)
        res = {}
        for c in sc.conflicts():
            res[(c.sig, c.objid)] = dc.compare(c)
        weap = [v for (sig, _o), v in res.items() if sig == 'WEAP'][0]
        self.assertEqual(weap['status'], 'forwardable')
        lost = {l['plugin']: l['lost'] for l in weap['losers']}
        self.assertTrue(any(f == 'DATA.damage' for f, _k, _d in lost['ModA.esp']))
        npc = [v for (sig, _o), v in res.items() if sig == 'NPC_'][0]
        self.assertEqual(npc['status'], 'clash')
        lvl = [v for (sig, _o), v in res.items() if sig == 'LVLI'][0]
        self.assertEqual(lvl['status'], 'lists')
        rev = sc.official_reverts()['Reverter.esp']
        fields = dc.reverted_fields(rev['keys'][0], rev['fixers'])
        self.assertEqual(fields, ['DATA.value'])

    def test_advice(self):
        m, sc = self.scanner()
        issues = m.validate()
        confl = sc.conflicts()
        _s, moves, _n = m.sort()
        adv = advice.from_validation(issues) + advice.from_sort(moves) + \
            advice.from_overridden_patches(sc.overridden_patches(confl)) + \
            advice.from_conflicts(confl, scanner=sc) + \
            advice.from_checks(sc.dirty(), sc.navmesh_cells(), sc.edid_duplicates(), sc.injected()[1],
                               sc.official_reverts(), sc) + \
            advice.from_eslify(eslify.analyse(m), 24, 254, eslify.procedure())
        adv = advice.sort_advice(adv)
        kinds = {a.kind for a in adv}
        for k in ('load-order', 'sort', 'patch-overridden', 'conflict:leveled', 'reverts-fixes', 'dirty',
                  'injected-collision', 'eslify-flag', 'eslify-compact'):
            self.assertIn(k, kinds)
        self.assertEqual(adv[0].priority, 1)
        self.assertEqual([a.priority for a in adv], sorted(a.priority for a in adv))
        for a in adv:
            json.dumps(a.as_dict())
        lv = [a for a in adv if a.kind == 'conflict:leveled'][0]
        self.assertTrue(any('esp merge' in h for h in lv.how))
        self.assertIn('bashed', lv.tools)


