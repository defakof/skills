        self.assertLess(names.index('ModB.esp'), names.index('WrongOrder.esp'))
        m2 = lorder.LoadOrderModel.from_sources(data=self.data, plugins_txt=out, userlist='')
        _o, moves2, _ = m2.sort()
        self.assertEqual(moves2, [])                                   # sorting the result changes nothing

