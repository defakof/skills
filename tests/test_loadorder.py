    def test_mo2_profile(self):
        inst = os.path.join(self.tmp, 'mo2')
        prof = os.path.join(inst, 'profiles', 'Default')
        os.makedirs(prof)
        for mod, plugin in (('Low Mod', 'Shared.esp'), ('High Mod', 'Shared.esp'), ('Other', 'Other.esp')):
            d = os.path.join(inst, 'mods', mod)
            os.makedirs(d)
            shutil.copy(os.path.join(self.data, 'Eslable.esp'), os.path.join(d, plugin))
        with open(os.path.join(inst, 'ModOrganizer.ini'), 'w') as f:
            f.write('[General]\ngamePath=@ByteArray(%s)\n' % self.root.replace('\\', '\\\\'))
        with open(os.path.join(prof, 'modlist.txt'), 'w') as f:
            f.write('# This file was automatically generated by Mod Organizer.\n+High Mod\n-Other\n'
                    '+Low Mod\n+Separator_separator\n')
        with open(os.path.join(prof, 'plugins.txt'), 'w') as f:
            f.write('*Shared.esp\n*Other.esp\n')
        m = lorder.LoadOrderModel.from_sources(mo2_profile=prof, userlist='')
        self.assertEqual(m.manager, 'MO2')
        self.assertEqual(os.path.normcase(m.data_dir), os.path.normcase(self.data))
        e = m.by_name()['shared.esp']
        self.assertEqual(e.source, 'High Mod')                      # first line of modlist.txt wins
        self.assertIsNone(m.by_name()['other.esp'].path)             # its mod is disabled


