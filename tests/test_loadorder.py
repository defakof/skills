def file_crc(path):
    with open(path, 'rb') as f:
        return zlib.crc32(f.read()) & 0xFFFFFFFF


class LoBase(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.mkdtemp(prefix='esplo-')
        cls.cache = os.path.join(cls.tmp, 'cache')
        cls._old_cache = os.environ.get('ESP_CACHE_DIR')
        os.environ['ESP_CACHE_DIR'] = cls.cache
        cls.root = make_lo_fixture.build(os.path.join(cls.tmp, 'lo'))
        cls.data = os.path.join(cls.root, 'Data')
        cls.ptxt = os.path.join(cls.root, 'plugins.txt')

    @classmethod
    def tearDownClass(cls):
        if cls._old_cache is None:
            os.environ.pop('ESP_CACHE_DIR', None)
        else:
            os.environ['ESP_CACHE_DIR'] = cls._old_cache
        shutil.rmtree(cls.tmp, ignore_errors=True)

    def model(self, userlist='', **kw):
        return lorder.LoadOrderModel.from_sources(data=self.data, plugins_txt=self.ptxt, userlist=userlist, **kw)

    def userlist(self, text):
        path = os.path.join(self.tmp, 'userlist_%d.yaml' % (abs(hash(text)) % 10 ** 8))
        with open(path, 'w', encoding='utf-8') as f:
            f.write(text)
        return path

    def cli(self, *args):
        r = subprocess.run([sys.executable, ESP, *args], capture_output=True, encoding='utf-8', errors='replace',
                           env=dict(os.environ, ESP_CACHE_DIR=self.cache))
        self.assertEqual(r.returncode, 0, r.stderr + r.stdout)
        return r.stdout


class TestLoadOrderModel(LoBase):
    def test_effective_order(self):
        m = self.model()
        names = [e.name for e in m.effective_order()]
        self.assertEqual(names[:3], ['Skyrim.esm', 'Update.esm', 'ccTestSSE001-Example.esl'])
        self.assertNotIn('ccNotInstalled.esm', names)          # in Skyrim.ccc but not installed
        self.assertNotIn('InactiveMaster.esm', names)          # inactive
        self.assertNotIn('Removed.esp', names)                 # missing file
        # masters (ESM flag or .esm/.esl) load before regular plugins, whatever plugins.txt says
        self.assertLess(names.index('LateMaster.esm'), names.index('ModA.esp'))
        self.assertLess(names.index('Unofficial Skyrim Special Edition Patch.esp'), names.index('ModA.esp'))
        # a master-flagged plugin hoists the regular plugin it depends on
        self.assertEqual(names.index('HoistDep.esp') + 1, names.index('MasterNeedsEsp.esm'))
        self.assertLess(names.index('MasterNeedsEsp.esm'), names.index('ModA.esp'))

    def test_load_indices(self):
        m = self.model()
        idx = m.load_indices()
        self.assertEqual(idx['skyrim.esm'], '00')
        self.assertEqual(idx['cctestsse001-example.esl'], 'FE:000')
        self.assertEqual(idx['lightmod.esp'], 'FE:001')
        self.assertEqual(m.max_full(), 254)

    def test_validation(self):
        m = self.model()
        issues = m.validate()
        codes = {}
        for i in issues:
            codes.setdefault(i.code, []).append(i.plugin)
        self.assertIn('MissingMaster.esp', codes['missing-master'])
        self.assertIn('NeedsInactive.esp', codes['inactive-master'])
        self.assertEqual(sorted(codes['master-order']), ['Bashed Patch, 0.esp', 'WrongOrder.esp'])
        self.assertEqual(codes['esl-range'], ['BadLight.esp'])
        self.assertEqual(codes['le-header'], ['OldLE.esp'])
        self.assertEqual(codes['not-found'], ['Removed.esp'])
        self.assertEqual(codes['master-needs-nonmaster'], ['MasterNeedsEsp.esm'])
        self.assertEqual(codes['after-generated'], ['Bashed Patch, 0.esp'])
        self.assertIn('LateMaster.esm', codes['master-partition'])
        self.assertNotIn('LightMod.esp', codes.get('esl-range', []))
        for i in issues:
            self.assertIn(i.level, ('error', 'warning', 'info'))

    def test_stale_generated_patch(self):
        m = self.model()
        bp = os.path.join(self.data, 'Bashed Patch, 0.esp')
        st = os.stat(bp)
        old = time.time() - 3 * 86400
        try:
            os.utime(bp, (old, old))
            issues = self.model().validate()
            stale = [i for i in issues if i.code == 'stale-patch']
            self.assertEqual(len(stale), 1)
            self.assertIn('ModA.esp', stale[0].related)
        finally:
            os.utime(bp, (st.st_atime, st.st_mtime))
        self.assertFalse([i for i in m.validate() if i.code == 'stale-patch'])

    def test_sort(self):
        m = self.model()
        order, moves, _notes = m.sort()
        names = [e.name for e in order]
        moved = {e.name: r for e, r in moves}
        self.assertLess(names.index('ModB.esp'), names.index('WrongOrder.esp'))
        self.assertIn('WrongOrder.esp', moved)
        self.assertTrue(any('master of WrongOrder.esp' in r for r in moved['WrongOrder.esp']))
        # LOOT group "Dynamic Patches" (Bashed Patch) loads after every default-group plugin
        self.assertEqual(names[-1], 'Bashed Patch, 0.esp')
        # hard rules hold in the result
        pos = {n.lower(): i for i, n in enumerate(names)}
        for e in order:
            for mname in (e.scan.masters if e.scan else []):
                if mname.lower() in pos:
                    self.assertLess(pos[mname.lower()], pos[e.low], (mname, e.name))
        # plugins that did not need to move keep their relative order
        before = [e.name for e in m.effective_order() if e.name not in moved]
        after = [n for n in names if n not in moved]
        self.assertEqual(before, after)

    def test_generated_patch_order(self):
        from esplib import Plugin
        root = os.path.join(self.tmp, 'gen')
        shutil.copytree(self.root, root)
        data = os.path.join(root, 'Data')
        for n in ('Synthesis.esp', 'Synthesis_2.esp', 'Bashed Patch, 1.esp'):
            p = Plugin.new(n, ['Skyrim.esm'])
            p.path = os.path.join(data, n)
            p.save(backup=False)
        shutil.copy(os.path.join(data, 'Reverter.esp'), os.path.join(data, 'Reverter2.esp'))
        with open(os.path.join(root, 'plugins.txt'), 'a') as f:
            f.write('*Synthesis.esp\n*Reverter2.esp\n*Synthesis_2.esp\n*Bashed Patch, 1.esp\n')
        want = ['Reverter2.esp', 'Bashed Patch, 0.esp', 'Bashed Patch, 1.esp', 'Synthesis.esp', 'Synthesis_2.esp']
        for mlist_arg in (None, 'none'):
            m = lorder.LoadOrderModel.from_sources(data=data, plugins_txt=os.path.join(root, 'plugins.txt'),
                                                   userlist='', masterlist=mlist_arg)
            codes = {i.code for i in m.validate()}
            self.assertIn('generated-order', codes)
            self.assertIn('synthesis-split', codes)
            order, _moves, _ = m.sort()
            self.assertEqual([e.name for e in order][-5:], want, mlist_arg)

